import assert from 'node:assert/strict';
import {createHistory,HISTORY_KEY,HISTORY_LIMIT} from './dist/history.mjs';
import {units} from './dist/units.mjs';
import create from './dist/engine/coolprop.js';
import {solve} from './dist/engine/thermo.mjs';
const cp=await create({print:()=>{},printErr:()=>{}});
const result=solve(cp,{P:1e6,T:573.15}).states[0];
const memory=new Map();const storage={getItem:k=>memory.get(k)??null,setItem:(k,v)=>memory.set(k,v)};
const entry={id:'test-1',createdAt:new Date().toISOString(),inputs:{P:1e6,T:573.15},result,units:Object.fromEntries(Object.entries(units).map(([k,u])=>[k,u[0].label]))};
const history=createHistory(storage);assert.equal(history.add(entry),true);
entry.inputs.P=2e6;assert.equal(history.list()[0].inputs.P,1e6);
const reopened=createHistory(storage);assert.equal(reopened.list().length,1);assert.equal(reopened.list()[0].result.H,result.H);assert.equal(reopened.list()[0].units.T,'°C');
for(let i=0;i<105;i++)reopened.add({...entry,id:`test-${i}`});
assert.equal(reopened.list().length,HISTORY_LIMIT);assert.equal(reopened.list()[0].id,'test-104');assert.equal(createHistory(storage).list().length,HISTORY_LIMIT);
memory.set(HISTORY_KEY,JSON.stringify(Array.from({length:15},(_,i)=>({...entry,id:`legacy-${i}`}))));
assert.equal(createHistory(storage).list().length,10);assert.equal(JSON.parse(memory.get(HISTORY_KEY)).length,10);
memory.set(HISTORY_KEY,'not json');assert.equal(createHistory(storage).list().length,0);
memory.set(HISTORY_KEY,JSON.stringify([{id:'bad'}]));assert.equal(createHistory(storage).list().length,0);
const unavailable=createHistory({getItem(){throw Error('blocked');},setItem(){throw Error('blocked');}});
assert.equal(unavailable.add(entry),false);assert.equal(unavailable.list().length,1);
assert.equal(unavailable.remove(entry.id),false);assert.equal(unavailable.list().length,0);
unavailable.add(entry);assert.equal(unavailable.clear(),false);assert.equal(unavailable.list().length,0);
memory.clear();memory.set('unrelated-setting','keep');
const deletion=createHistory(storage);
deletion.add({...entry,id:'first'});deletion.add({...entry,id:'second'});deletion.add({...entry,id:'third'});
assert.equal(deletion.remove('second'),true);
assert.deepEqual(deletion.list().map(e=>e.id),['third','first']);
assert.deepEqual(createHistory(storage).list().map(e=>e.id),['third','first']);
deletion.remove('missing');assert.equal(deletion.list().length,2);
assert.equal(deletion.clear(),true);assert.deepEqual(deletion.list(),[]);
assert.deepEqual(createHistory(storage).list(),[]);assert.equal(memory.get('unrelated-setting'),'keep');
deletion.add({...entry,id:'after-clear'});assert.equal(createHistory(storage).list()[0].id,'after-clear');
console.log('History persistence, retention, single deletion, clear all and storage fallback passed.');
