import assert from 'node:assert/strict';
import create from './dist/engine/coolprop.js';
import {solve} from './dist/engine/thermo.mjs';
import {units} from './dist/units.mjs';
import {createReport} from './dist/report.mjs';
const cp=await create({print:()=>{},printErr:()=>{}});
const snapshot={createdAt:'2026-11-11T10:00:00.000Z',inputs:{P:1e6,T:573.15},units:Object.fromEntries(Object.entries(units).map(([k,u])=>[k,u[0].label])),result:solve(cp,{P:1e6,T:573.15}).states[0]};
const before=structuredClone(snapshot);
const si=createReport(snapshot);
assert.match(si.text,/State: Superheated steam/);
assert.match(si.text,/Enthalpy: 3051.703 kJ\/kg/);
assert.match(si.text,/Saturation temperature at 1 MPa\(a\): 179.8856 °C/);
assert.match(si.text,/Surface tension: N\/A N\/m/);
assert.equal(si.rows.filter(r=>r[0]==='Input').length,2);
assert.equal(si.rows.filter(r=>r[0]==='Output').length,16);
assert.equal(si.rows.filter(r=>r[0]==='Saturation').length,2);
assert.ok(si.csv.startsWith('\uFEFF"Section","Property","Value","Unit"\r\n'));
assert.match(si.csv,/"Output","Vapor fraction","1","fraction"/);
assert.equal(si.filename,'steam-properties-2026-11-11T10-00-00-000Z');
assert.deepEqual(snapshot,before);
const converted=createReport({...snapshot,units:{...snapshot.units,P:'bar(a)',T:'°F',Q:'%'}});
assert.match(converted.text,/Pressure: 10 bar\(a\)/);
assert.match(converted.text,/Temperature: 572 °F/);
assert.match(converted.text,/Vapor fraction: 100 %/);
assert.match(converted.text,/Saturation temperature at 10 bar\(a\): 355.7941 °F/);
const wet=createReport({...snapshot,inputs:{P:1e6,Q:.25},result:solve(cp,{P:1e6,Q:.25}).states[0]});
assert.match(wet.text,/Vapor fraction: 0.25 fraction/);
assert.match(wet.text,/Heat capacity Cp: N\/A/);
assert.equal(wet.rows.filter(r=>r[0]==='Saturation').length,0);
const liquid=createReport({...snapshot,inputs:{P:1e6,T:373.15},result:solve(cp,{P:1e6,T:373.15}).states[0]});
assert.match(liquid.text,/State: Subcooled liquid/);assert.match(liquid.text,/Vapor fraction: 0 fraction/);
assert.match(liquid.text,/Saturation pressure at 100 °C: 0.101418 MPa\(a\)/);
const critical=createReport({...snapshot,inputs:{P:25e6,T:773.15},result:solve(cp,{P:25e6,T:773.15}).states[0]});
assert.match(critical.text,/Vapor fraction: N\/A/);
assert.throws(()=>createReport(null));
console.log('Exports: selected units, inputs, all outputs, saturation references, phase conventions, timestamps and snapshot isolation passed.');
